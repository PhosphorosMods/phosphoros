package lucifertotem.hillman;

import lucifertotem.LTConfig;
import lucifertotem.LuciferTotem;
import lucifertotem.world.LightfallChunkGenerator;
import net.minecraft.nbt.NBTTagCompound;
import net.minecraft.tileentity.TileEntity;
import net.minecraft.tileentity.TileEntityChest;
import net.minecraft.tileentity.TileEntityMobSpawner;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;
import net.minecraft.world.WorldServer;
import net.minecraft.world.chunk.Chunk;
import net.minecraft.world.storage.WorldSavedData;

import java.util.*;

/**
 * Where the Lightfall's structures are. Every structure generated since 1.1.0 is recorded here; for places not yet
 * generated (or generated by 1.0.x) locate() predicts the per-chunk structure roll exactly like LightfallStructures,
 * checks already-populated candidates by their tile entities, and populates up to a small budget of new candidate
 * chunks to confirm. Oracles therefore only ever point at places that really exist.
 */
public class StructureIndex extends WorldSavedData {
    public static final String NAME = "lucifertotem_structures";
    public static final String[] TYPES = {"morningstar_citadel", "fallen_spire", "sunken_shrine", "light_shrine", "trophonius_pit", "delphic_vent", "witch_circle"};
    /** 1.3.0 structures: their own per-chunk roll (salt 0x130B), so the older rolls above are unchanged */
    public static final String[] TYPES130 = {"bacchic_fountain", "crossroads_shrine", "mystery_hall", "on_air_studio", "band_camp", "asklepieion"};
    public static boolean is130(String type) { for (String t : TYPES130) if (t.equals(type)) return true; return false; }
    public static int[] band130(String type) {
        LTConfig.V130 v = LTConfig.v130;
        int[] w = {v.bacchicFountain, v.crossroads, v.mysteryHall, v.onAirStudio, v.bandCamp, v.asklepieion};
        int lo = 0;
        for (int i = 0; i < TYPES130.length; i++) { if (TYPES130[i].equals(type)) return new int[]{lo, lo + w[i]}; lo += w[i]; }
        return null;
    }
    public static String typeForRoll130(int roll) { for (String t : TYPES130) { int[] b = band130(t); if (roll >= b[0] && roll < b[1]) return t; } return null; }
    public static int roll130(long seed, int cx, int cz) { return LightfallChunkGenerator.chunkRandom(seed, cx, cz, 0x130BL).nextInt(1000); }
    private final Map<String, Set<Long>> map = new HashMap<>();
    /** chunks whose prediction was checked and found empty (in memory only) */
    private final Set<Long> checkedEmpty = new HashSet<>();

    public StructureIndex(String name) { super(name); }

    public static StructureIndex get(World w) {
        StructureIndex i = (StructureIndex) w.getPerWorldStorage().getOrLoadData(StructureIndex.class, NAME);
        if (i == null) { i = new StructureIndex(NAME); w.getPerWorldStorage().setData(NAME, i); }
        return i;
    }

    public static void record(World w, String type, BlockPos at) {
        if (w.isRemote) return;
        StructureIndex i = get(w);
        i.map.computeIfAbsent(type, k -> new LinkedHashSet<>()).add(at.toLong());
        i.markDirty();
    }

    public Set<Long> all(String type) { return map.getOrDefault(type, Collections.emptySet()); }

    @Override
    public void readFromNBT(NBTTagCompound t) {
        map.clear();
        for (String k : t.getKeySet()) {
            Set<Long> s = new LinkedHashSet<>();
            net.minecraft.nbt.NBTTagList l = t.getTagList(k, 4);
            for (int i = 0; i < l.tagCount(); i++) s.add(((net.minecraft.nbt.NBTTagLong) l.get(i)).getLong());
            map.put(k, s);
        }
    }

    @Override
    public NBTTagCompound writeToNBT(NBTTagCompound t) {
        for (Map.Entry<String, Set<Long>> e : map.entrySet()) {
            net.minecraft.nbt.NBTTagList l = new net.minecraft.nbt.NBTTagList();
            for (long v : e.getValue()) l.appendTag(new net.minecraft.nbt.NBTTagLong(v));
            t.setTag(e.getKey(), l);
        }
        return t;
    }

    /** the roll band [lo, hi) of a type (same order and values as LightfallStructures.tryGenerate) */
    public static int[] band(String type) {
        LTConfig.Structures c = LTConfig.structures;
        LTConfig.Structures110 n = LTConfig.structures110;
        int[] w = {c.morningstarCitadel, c.fallenSpire, c.sunkenShrine, c.lightShrine, n.trophoniusPit, n.delphicVent, n.witchCircle};
        int lo = 0;
        for (int i = 0; i < TYPES.length; i++) {
            if (TYPES[i].equals(type)) return new int[]{lo, lo + w[i]};
            lo += w[i];
        }
        return null;
    }

    public static String typeForRoll(int roll) {
        for (String t : TYPES) { int[] b = band(t); if (roll >= b[0] && roll < b[1]) return t; }
        return null;
    }

    public static int roll(long seed, int cx, int cz) { return LightfallChunkGenerator.chunkRandom(seed, cx, cz, 0x57A7L).nextInt(1000); }

    public static int lastForced = 0;

    /** nearest real structure of a type within radiusChunks; may populate up to forceBudget new candidate chunks */
    public static BlockPos locate(WorldServer w, String type, BlockPos from, int radiusChunks, int forceBudget) {
        if (w.provider.getDimension() != LuciferTotem.dimId) return null;
        // the Library's place is known from the seed alone (it is large and rare: look further)
        if ("library".equals(type)) { lastForced = 0; return lucifertotem.world.LibraryGen.nearest(w.getSeed(), from, Math.max(radiusChunks, 160) * 16); }
        StructureIndex idx = get(w);
        BlockPos best = nearest(idx.all(type), from, radiusChunks * 16);
        boolean v130 = is130(type);
        int[] b = v130 ? band130(type) : band(type);
        if (b == null || b[1] <= b[0]) return best;
        double bestD = best == null ? Double.MAX_VALUE : best.distanceSq(from);
        int fcx = from.getX() >> 4, fcz = from.getZ() >> 4;
        List<int[]> cand = new ArrayList<>();
        long seed = w.getSeed();
        for (int dx = -radiusChunks; dx <= radiusChunks; dx++) for (int dz = -radiusChunks; dz <= radiusChunks; dz++) {
            int cx = fcx + dx, cz = fcz + dz;
            int r = v130 ? roll130(seed, cx, cz) : roll(seed, cx, cz);
            if (r >= b[0] && r < b[1]) cand.add(new int[]{cx, cz, dx * dx + dz * dz});
        }
        cand.sort(Comparator.comparingInt(a -> a[2]));
        lastForced = 0;
        for (int[] c : cand) {
            int wx = c[0] * 16 + 16, wz = c[1] * 16 + 16; // window centre
            double d = (wx - from.getX()) * (double) (wx - from.getX()) + (wz - from.getZ()) * (double) (wz - from.getZ());
            if (d > bestD + 32 * 32) break; // candidates are sorted; nothing closer remains
            long key = ChunkKey(c[0], c[1]);
            if (idx.checkedEmpty.contains(key)) continue;
            boolean populated = isPopulated(w, c[0], c[1]);
            if (!populated) {
                if (lastForced >= forceBudget) continue;
                lastForced++;
                populate(w, c[0], c[1]); // generation records it in the index if the site fits
                BlockPos got = inWindow(idx.all(type), c[0], c[1]);
                if (got != null) { if (got.distanceSq(from) < bestD) { bestD = got.distanceSq(from); best = got; } }
                else idx.checkedEmpty.add(key);
                continue;
            }
            BlockPos got = inWindow(idx.all(type), c[0], c[1]);
            if (got == null) got = signature(w, type, c[0], c[1]);
            if (got != null) {
                record(w, type, got);
                if (got.distanceSq(from) < bestD) { bestD = got.distanceSq(from); best = got; }
            } else idx.checkedEmpty.add(key);
        }
        return best;
    }

    static long ChunkKey(int x, int z) { return ((long) x << 32) ^ (z & 0xffffffffL); }

    static BlockPos nearest(Set<Long> s, BlockPos from, int maxDist) {
        BlockPos best = null; double bd = (double) maxDist * maxDist;
        for (long l : s) { BlockPos p = BlockPos.fromLong(l); double d = sq(p, from); if (d < bd) { bd = d; best = p; } }
        return best;
    }

    static double sq(BlockPos a, BlockPos b) { double dx = a.getX() - b.getX(), dz = a.getZ() - b.getZ(); return dx * dx + dz * dz; }

    static BlockPos inWindow(Set<Long> s, int cx, int cz) {
        int bx = cx * 16 + 8, bz = cz * 16 + 8;
        for (long l : s) { BlockPos p = BlockPos.fromLong(l); if (p.getX() >= bx && p.getX() < bx + 16 && p.getZ() >= bz && p.getZ() < bz + 16) return p; }
        return null;
    }

    static boolean isPopulated(WorldServer w, int cx, int cz) {
        if (!w.isChunkGeneratedAt(cx, cz)) return false;
        Chunk c = w.getChunk(cx, cz);
        return c.isTerrainPopulated();
    }

    /** loading the window's four chunks makes chunk (cx,cz) populate */
    static void populate(WorldServer w, int cx, int cz) {
        w.getChunk(cx, cz); w.getChunk(cx + 1, cz); w.getChunk(cx, cz + 1); w.getChunk(cx + 1, cz + 1);
    }

    /** pre-1.1 structure check: our spawners / loot chests inside the populate window */
    static BlockPos signature(WorldServer w, String type, int cx, int cz) {
        if (is130(type)) return null;   // 1.3.0 places did not exist before 1.3.0; new ones are always recorded
        int bx = cx * 16 + 8, bz = cz * 16 + 8;
        for (int ox = 0; ox <= 1; ox++) for (int oz = 0; oz <= 1; oz++) {
            Chunk c = w.getChunk(cx + ox, cz + oz);
            for (TileEntity te : c.getTileEntityMap().values()) {
                BlockPos p = te.getPos();
                if (p.getX() < bx || p.getX() >= bx + 16 || p.getZ() < bz || p.getZ() >= bz + 16) continue;
                if (te instanceof TileEntityMobSpawner && p.getY() > 50 && !te.writeToNBT(new NBTTagCompound()).getCompoundTag("SpawnData").getString("id").endsWith("enchantress")) return p;
                if (type.equals("light_shrine") && te instanceof TileEntityChest && p.getY() > 50) return p;
            }
        }
        return null;
    }
}
